/// Параметры вкладки Телемоста, хранимые в SharedPreferences нотифаером.
///
/// Раньше здесь жили параметры выбора комнаты — они переехали в нативную
/// часть (relay находит комнату сам). Осталась только
/// настройка видео-туннеля.
class WbstreamSettings {
  const WbstreamSettings({
    this.vp8Fps = 60,
    this.vp8Batch = 18,
    this.dualTrack = true,
    this.reliable = false,
  });

  /// Параметры VP8-туннеля (60 fps / batch 18 — измеренный оптимум на
  /// устройстве: ~7.8/3.6 Мбит/с, 0% потерь; старые 12/8 упирались в ~1 Мбит/с).
  final int vp8Fps;
  final int vp8Batch;
  final bool dualTrack;
  final bool reliable;

  WbstreamSettings copyWith({
    int? vp8Fps,
    int? vp8Batch,
    bool? dualTrack,
    bool? reliable,
  }) =>
      WbstreamSettings(
        vp8Fps: vp8Fps ?? this.vp8Fps,
        vp8Batch: vp8Batch ?? this.vp8Batch,
        dualTrack: dualTrack ?? this.dualTrack,
        reliable: reliable ?? this.reliable,
      );

  Map<String, dynamic> toJson() => {
        'vp8Fps': vp8Fps,
        'vp8Batch': vp8Batch,
        'dualTrack': dualTrack,
        'reliable': reliable,
      };

  factory WbstreamSettings.fromJson(Map<String, dynamic> json) => WbstreamSettings(
        vp8Fps: (json['vp8Fps'] as num?)?.toInt() ?? 60,
        vp8Batch: (json['vp8Batch'] as num?)?.toInt() ?? 18,
        dualTrack: json['dualTrack'] as bool? ?? true,
        reliable: json['reliable'] as bool? ?? false,
      );
}

/// Local SOCKS5 endpoint of the relay, generated by the native side per start.
class WbstreamSocks {
  const WbstreamSocks({
    required this.host,
    required this.port,
    required this.user,
    required this.pass,
  });

  final String host;
  final int port;
  final String user;
  final String pass;

  factory WbstreamSocks.fromMap(Map<dynamic, dynamic> map) => WbstreamSocks(
        host: map['host'] as String,
        port: (map['port'] as num).toInt(),
        user: map['user'] as String,
        pass: map['pass'] as String,
      );
}

/// State machine for the Telemost tunnel mode (plain Dart, no codegen).
sealed class WbstreamTunnelState {
  const WbstreamTunnelState();
}

/// Mode is off.
class WbstreamIdle extends WbstreamTunnelState {
  const WbstreamIdle();
}

/// Relay process is starting (STATUS:READY seen or start() in flight).
class WbstreamStarting extends WbstreamTunnelState {
  const WbstreamStarting();
}

/// Joining the room (STATUS:CONNECTING).
class WbstreamConnecting extends WbstreamTunnelState {
  const WbstreamConnecting();
}

/// STATUS:TUNNEL_CONNECTED — local SOCKS5 is up.
class WbstreamConnected extends WbstreamTunnelState {
  const WbstreamConnected(this.socks);

  final WbstreamSocks socks;
}

/// STATUS:TUNNEL_LOST — tunnel dropped; treated as fatal for the VPN
/// session (fallback to a regular server).
class WbstreamLost extends WbstreamTunnelState {
  const WbstreamLost();
}

class WbstreamError extends WbstreamTunnelState {
  const WbstreamError(this.message);

  final String message;
}
