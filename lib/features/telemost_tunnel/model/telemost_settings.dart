/// Settings for the Telemost tunnel mode (whitelist-bypass relay running as
/// telemost-headless-joiner). Persisted in SharedPreferences by the notifier.
class TelemostSettings {
  const TelemostSettings({
    this.joinLink = '',
    this.displayName = 'AxiOm',
    this.vp8Fps = 60,
    this.vp8Batch = 18,
    this.dualTrack = true,
    this.reliable = false,
    this.diskUrlA = defaultDiskUrlA,
    this.diskUrlB = defaultDiskUrlB,
    this.lastGoodSlot = '',
  });

  /// Default public Yandex.Disk links that serve the current server-side
  /// conference links (A/B failover pair).
  static const defaultDiskUrlA = 'https://yadi.sk/d/2mC3IWwch1ZUSw';
  static const defaultDiskUrlB = 'https://yadi.sk/d/ihGW6Bd5a-PJdw';

  /// Manual conference link, e.g. `https://telemost.yandex.ru/j/<id>`.
  /// Used only as a fallback when both disk slots fail.
  final String joinLink;

  /// Public Yandex.Disk links (files whose content is the join link).
  final String diskUrlA;
  final String diskUrlB;

  /// 'A' or 'B' — the slot that connected last time (tried first).
  /// Empty when neither has succeeded yet. Not user-editable.
  final String lastGoodSlot;

  /// Name shown in the call.
  final String displayName;

  /// VP8 data tunnel parameters (60 fps / batch 18 measured best on-device:
  /// ~7.8/3.6 Mbps, 0% loss; the old 12/8 combo caps at ~1 Mbps).
  final int vp8Fps;
  final int vp8Batch;
  final bool dualTrack;
  final bool reliable;

  TelemostSettings copyWith({
    String? joinLink,
    String? displayName,
    int? vp8Fps,
    int? vp8Batch,
    bool? dualTrack,
    bool? reliable,
    String? diskUrlA,
    String? diskUrlB,
    String? lastGoodSlot,
  }) =>
      TelemostSettings(
        joinLink: joinLink ?? this.joinLink,
        displayName: displayName ?? this.displayName,
        vp8Fps: vp8Fps ?? this.vp8Fps,
        vp8Batch: vp8Batch ?? this.vp8Batch,
        dualTrack: dualTrack ?? this.dualTrack,
        reliable: reliable ?? this.reliable,
        diskUrlA: diskUrlA ?? this.diskUrlA,
        diskUrlB: diskUrlB ?? this.diskUrlB,
        lastGoodSlot: lastGoodSlot ?? this.lastGoodSlot,
      );

  /// True for links the relay can actually join.
  static bool isValidJoinLink(String link) {
    final uri = Uri.tryParse(link.trim());
    if (uri == null || !uri.hasScheme) return false;
    return uri.host.endsWith('telemost.yandex.ru') && uri.pathSegments.contains('j');
  }

  Map<String, dynamic> toJson() => {
        'joinLink': joinLink,
        'displayName': displayName,
        'vp8Fps': vp8Fps,
        'vp8Batch': vp8Batch,
        'dualTrack': dualTrack,
        'reliable': reliable,
        'diskUrlA': diskUrlA,
        'diskUrlB': diskUrlB,
        'lastGoodSlot': lastGoodSlot,
      };

  factory TelemostSettings.fromJson(Map<String, dynamic> json) => TelemostSettings(
        joinLink: json['joinLink'] as String? ?? '',
        displayName: json['displayName'] as String? ?? 'AxiOm',
        vp8Fps: (json['vp8Fps'] as num?)?.toInt() ?? 60,
        vp8Batch: (json['vp8Batch'] as num?)?.toInt() ?? 18,
        dualTrack: json['dualTrack'] as bool? ?? true,
        reliable: json['reliable'] as bool? ?? false,
        diskUrlA: json['diskUrlA'] as String? ?? defaultDiskUrlA,
        diskUrlB: json['diskUrlB'] as String? ?? defaultDiskUrlB,
        lastGoodSlot: json['lastGoodSlot'] as String? ?? '',
      );
}

/// Local SOCKS5 endpoint of the relay, generated by the native side per start.
class TelemostSocks {
  const TelemostSocks({
    required this.host,
    required this.port,
    required this.user,
    required this.pass,
  });

  final String host;
  final int port;
  final String user;
  final String pass;

  factory TelemostSocks.fromMap(Map<dynamic, dynamic> map) => TelemostSocks(
        host: map['host'] as String,
        port: (map['port'] as num).toInt(),
        user: map['user'] as String,
        pass: map['pass'] as String,
      );
}

/// State machine for the Telemost tunnel mode (plain Dart, no codegen).
sealed class TelemostTunnelState {
  const TelemostTunnelState();
}

/// Mode is off.
class TelemostIdle extends TelemostTunnelState {
  const TelemostIdle();
}

/// Relay process is starting (STATUS:READY seen or start() in flight).
class TelemostStarting extends TelemostTunnelState {
  const TelemostStarting({this.slot, this.failedSlot});

  /// Slot being tried: 'on-demand' for a freshly created conference,
  /// 'A'/'B' for disk slots, null for the manual/legacy path.
  final String? slot;

  /// Slot that just failed before this attempt (for the status line).
  final String? failedSlot;
}

/// Joining the call (STATUS:CONNECTING).
class TelemostConnecting extends TelemostTunnelState {
  const TelemostConnecting({this.slot});

  /// Slot being tried: 'on-demand' for a freshly created conference,
  /// 'A'/'B' for disk slots, null for the manual/legacy path.
  final String? slot;
}

/// STATUS:TUNNEL_CONNECTED — local SOCKS5 is up.
class TelemostConnected extends TelemostTunnelState {
  const TelemostConnected(this.socks);

  final TelemostSocks socks;
}

/// STATUS:TUNNEL_LOST — tunnel dropped; treated as fatal for the VPN
/// session (fallback to a regular server).
class TelemostLost extends TelemostTunnelState {
  const TelemostLost();
}

class TelemostError extends TelemostTunnelState {
  const TelemostError(this.message);

  final String message;
}
